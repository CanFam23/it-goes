CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE access_code (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code varchar(8) NOT NULL UNIQUE,
    email varchar(255) UNIQUE,
    created_at timestamp(6),
    expires_at timestamp(6),
    used_at timestamp(6),
    used boolean NOT NULL
);

CREATE TABLE image (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_name varchar(255) NOT NULL,
    s3key varchar(255) NOT NULL
);

CREATE TABLE it_goes_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_image_id bigint UNIQUE REFERENCES image(id),
    email varchar(255) NOT NULL UNIQUE,
    first_name varchar(255) NOT NULL,
    hashed_password_string varchar(255) NOT NULL,
    last_name varchar(255) NOT NULL,
    username varchar(255) NOT NULL UNIQUE
);

CREATE TABLE location (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(255) NOT NULL,
    state smallint NOT NULL CHECK (state BETWEEN 0 AND 7),
    country smallint NOT NULL CHECK (country BETWEEN 0 AND 2),
    location geometry(Point, 4326)
);

CREATE TABLE season (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_date date NOT NULL,
    end_date date NOT NULL
);

CREATE TABLE social_link (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    platform_enum smallint NOT NULL CHECK (platform_enum BETWEEN 0 AND 2),
    it_goes_user_id bigint REFERENCES it_goes_user(id),
    url varchar(255) NOT NULL
);

CREATE TABLE trip (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title varchar(255) NOT NULL,
    description oid NOT NULL,
    date_of_trip date NOT NULL,
    date_posted date NOT NULL,
    date_updated date NOT NULL,
    route geometry,
    author_id bigint REFERENCES it_goes_user(id),
    location_id bigint REFERENCES location(id),
    season_id bigint REFERENCES season(id),
    cover_image_key varchar(255) NOT NULL
);

CREATE TABLE image_trip (
    image_id bigint NOT NULL REFERENCES image(id),
    trip_id bigint NOT NULL REFERENCES trip(id),
    PRIMARY KEY (image_id, trip_id)
);

CREATE TABLE trip_users (
    trip_id bigint NOT NULL REFERENCES trip(id),
    user_id bigint NOT NULL REFERENCES it_goes_user(id),
    PRIMARY KEY (trip_id, user_id)
);
