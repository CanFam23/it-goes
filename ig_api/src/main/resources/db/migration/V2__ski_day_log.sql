CREATE TABLE ski_day_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES it_goes_user(id),
    location_id bigint NOT NULL REFERENCES location(id),
    ski_date date NOT NULL,
    CONSTRAINT uq_ski_day_user_date_location UNIQUE (user_id, ski_date, location_id)
);

CREATE INDEX idx_ski_day_user_date ON ski_day_log (user_id, ski_date);
